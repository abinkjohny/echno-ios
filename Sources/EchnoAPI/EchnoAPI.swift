// EchnoAPI — the generated wire layer.
//
// Everything callable in this module is produced at build time by
// swift-openapi-generator from `openapi.json`, which `Scripts/sync-openapi.sh`
// vendors from echno-backend. Nothing here is written by hand.
//
// To change what is generated:
//   · new endpoints on the backend → re-run Scripts/sync-openapi.sh
//   · a new module's operations     → add its tag to openapi-generator-config.yaml
//
// `openapi.source` records the backend commit the document came from, so a
// regeneration is traceable.
//
// Consumers do not use these types directly. EchnoCore maps them into domain
// types first — see local-docs/ios-action-plan.md §1 for why.
